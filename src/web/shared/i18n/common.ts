export const useT = createUseT(commonCatalogs);

const STANDARD_STATUSES = ['backlog', 'todo', 'in-progress', 'done'] as const;
type StandardStatus = (typeof STANDARD_STATUSES)[number];

function isStandard(status: string): status is StandardStatus {
  return (STANDARD_STATUSES as readonly string[]).includes(status);
}

/**
 * How a status is written: the four standard ones in the language shown, any other as the
 * person configured it. Only the label changes; the value sent to the board never does.
 */
export function useStatusLabel(): (status: string) => string {
  const t = useT();
  return (status) => (isStandard(status) ? t(`status.${status}`) : status);
}
